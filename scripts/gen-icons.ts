type Node = [string, Record<string, string>];
const dir = process.argv[2];
if (!dir) throw new Error("Pass the path to the lucide-static icons directory: npx tsx scripts/gen-icons.ts /path/to/icons");

function read(file: string): Node[] {
  const svg = fs.readFileSync(path.join(dir!, `${file}.svg`), "utf8");
  const $ = cheerio.load(svg, { xmlMode: true });
  const nodes: Node[] = [];
  $("svg").children().each((_, el) => {
    if (el.type !== "tag") return;
    nodes.push([el.name, { ...el.attribs }]);
  });
  if (!nodes.length) throw new Error(`Icon ${file} has no shapes`);
  return nodes;
}

const emit = (name: string, map: Record<string, string>) => {
  const entries = Object.entries(map).map(([k, f]) => `  ${JSON.stringify(k)}: ${JSON.stringify(read(f))},`);
  return `export const ${name}: Record<string, IconShape[]> = {\n${entries.join("\n")}\n};\n`;
};

